def metade(n):
    met = n / 2
    return met

def dobro(n):
    dob = n * 2
    return dob

def aumentar(n=0, a=0):
    porcentagem = a / 100
    aumento = n * porcentagem
    total = n + aumento
    return total

def diminuir(n=0, a=0):
    porcentagem = a / 100
    menos = n * porcentagem
    total = n - menos
    return total

